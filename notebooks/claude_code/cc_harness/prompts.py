def build_system_prompt(*policy_sections):
    """마크다운 골격에 `##` 정책 하위 섹션들을 끼워 조립한다.

    policy_sections는 `# 도구 사용 정책` 아래, 상시 섹션인 `## 병렬 호출` 뒤에 순서대로
    들어간다 (레지스트리 고지 → 위임 정책 → 할일 관리 — 도구를 소개하는 섹션이 그 도구를
    쓰는 정책보다 앞).
    """
